// Regenerates src/data.ts from two independent open-source BS calendars.
//
//   npm run generate
//
// Rules:
//   * A year is VERIFIED only if both libraries agree on all 12 month lengths
//     AND the year is on or before LAST_OFFICIAL_YEAR (the last year whose
//     official calendar from Nepal Panchanga Nirnayak Vikas Samiti has been
//     published and checked).
//   * Later years are PROVISIONAL (projections). They come from `bikram-sambat`,
//     whose 2084 values match two independent public calendars checked on
//     2026-10-29. Payroll and leave code must warn when a provisional year is used.
//   * When the official calendar for a new year is published, put its 12 month
//     lengths in OFFICIAL_OVERRIDES below, raise LAST_OFFICIAL_YEAR and re-run.
//     (HR can also correct a year at runtime in the bs_calendar_months table.)

import { createRequire } from 'node:module';
import { writeFileSync } from 'node:fs';

const require = createRequire(import.meta.url);
const { dateConfigMap: A } = require('nepali-date-converter/dist/lib/date-config.js');
const B = require('bikram-sambat');

const LAST_OFFICIAL_YEAR = 2083;
const FIRST_YEAR = 2000;
const LAST_YEAR = 2090;
/** Official lengths that override both libraries, e.g. { 2084: [31,31,32,31,31,30,30,30,29,30,30,30] } */
const OFFICIAL_OVERRIDES = {};

const NAMES = ['Baisakh','Jestha','Asar','Shrawan','Bhadra','Aswin','Kartik','Mangsir','Poush','Magh','Falgun','Chaitra'];
const rows = [];
for (let y = FIRST_YEAR; y <= LAST_YEAR; y++) {
  const a = A[y] ? NAMES.map((n) => A[y][n]) : null;
  const b = NAMES.map((_, i) => B.daysInMonth(y, i + 1));
  const override = OFFICIAL_OVERRIDES[y];
  let lengths, status;
  if (override) {
    lengths = override; status = 'verified';
  } else if (y <= LAST_OFFICIAL_YEAR) {
    if (!a || a.join() !== b.join()) throw new Error(`Sources disagree for verified year ${y}; resolve before release`);
    lengths = b; status = 'verified';
  } else {
    lengths = b; status = 'provisional';
  }
  rows.push(`  ${y}: { status: '${status}', days: [${lengths.join(', ')}] },`);
}

const out = `// GENERATED by scripts/generate-data.mjs — do not edit by hand.
// Verified years: ${FIRST_YEAR}–${LAST_OFFICIAL_YEAR} (two independent sources agree, official calendar published).
// Provisional years: ${LAST_OFFICIAL_YEAR + 1}–${LAST_YEAR} (projections; replace with the official calendar when published).

export type YearStatus = 'verified' | 'provisional';

/** Day 1 of BS ${FIRST_YEAR} (1 Baisakh) in AD. */
export const BS_EPOCH_AD = '1943-04-14';
export const FIRST_BS_YEAR = ${FIRST_YEAR};
export const LAST_BS_YEAR = ${LAST_YEAR};
export const LAST_VERIFIED_BS_YEAR = ${LAST_OFFICIAL_YEAR};

export const MONTH_TABLE: Record<number, { status: YearStatus; days: readonly number[] }> = {
${rows.join('\n')}
};
`;
writeFileSync(new URL('../src/data.ts', import.meta.url), out);
console.log(`wrote src/data.ts (${rows.length} years)`);
