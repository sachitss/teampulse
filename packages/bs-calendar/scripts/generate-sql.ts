// Emits the seed for public.bs_calendar_months from the same table the
// TypeScript library uses, so SQL and TypeScript can never disagree.
//   npm run sql   →  supabase/seed/00_bs_calendar.sql
import { FIRST_BS_YEAR, LAST_BS_YEAR, monthRange, yearStatus } from '../src/index.ts';

const rows: string[] = [];
for (let y = FIRST_BS_YEAR; y <= LAST_BS_YEAR; y++) {
  for (let m = 1; m <= 12; m++) {
    const r = monthRange(y, m);
    rows.push(`(${y},${m},${r.days},'${r.startAd}','${yearStatus(y)}')`);
  }
}
console.log(`-- GENERATED by packages/bs-calendar (npm run sql). Do not edit by hand.
-- To correct a provisional year after the official calendar is published, update
-- the rows for that year (and re-derive ad_start for later years with
-- public.bs_calendar_recompute_starts()), or regenerate from the library.
insert into public.bs_calendar_months (bs_year, bs_month, days, ad_start, status) values
${rows.join(',\n')}
on conflict (bs_year, bs_month) do update
  set days = excluded.days, ad_start = excluded.ad_start, status = excluded.status;`);
